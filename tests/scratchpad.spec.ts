import { expect } from '@playwright/test';
import { test, mutationHeaders } from './fixtures';
import type { Scratchpad } from '../shared/scratchpad';

test('scratchpad autosaves Markdown, toggles nested tasks and survives close/reload/clear undo', async ({ page, request }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '打开随手记', exact: true }).click();
  const panel = page.getByRole('complementary', { name: '随手记', exact: true });
  const content = '# 今天\n\n- [ ] 第一件事\n  - [ ] 子任务\n\n**重要**\n\n```sh\npwd\n```\n';
  await panel.getByRole('button', { name: '源码', exact: true }).click();
  const editor = panel.getByRole('textbox', { name: '随手记内容' });
  await expect(editor).toBeEnabled();
  await editor.fill(content);
  // Closing immediately must not cancel an outstanding save.
  await panel.getByRole('button', { name: '关闭随手记' }).click();
  await expect.poll(async () => ((await (await request.get('/api/scratchpad')).json()) as Scratchpad).content).toBe(content);
  await page.getByRole('button', { name: '打开随手记', exact: true }).click();
  await expect(editor).toHaveValue(content);
  await panel.getByRole('button', { name: '预览', exact: true }).click();
  await expect(panel.getByRole('heading', { name: '今天' })).toBeVisible();
  await expect(panel.locator('strong').filter({ hasText: '重要' })).toBeVisible();
  await panel.getByRole('checkbox').nth(1).check();
  await expect(panel.getByRole('checkbox').first()).not.toBeChecked();
  const toggled = content.replace('- [ ] 子任务', '- [x] 子任务');
  await expect.poll(async () => ((await (await request.get('/api/scratchpad')).json()) as Scratchpad).content).toBe(toggled);
  await panel.getByRole('button', { name: '源码', exact: true }).click();
  const splitter = page.getByRole('separator', { name: '调整预览面板宽度' });
  await splitter.focus(); await splitter.press('ArrowLeft');
  await expect(splitter).toHaveAttribute('aria-valuenow', '584');
  await page.reload();
  await expect(panel).toBeVisible();
  await expect(editor).toHaveValue(toggled);
  await expect(splitter).toHaveAttribute('aria-valuenow', '584');
  await panel.getByRole('button', { name: '清空随手记' }).click();
  await panel.getByRole('button', { name: '取消', exact: true }).click();
  await expect(editor).toHaveValue(toggled);
  await panel.getByRole('button', { name: '清空随手记' }).click();
  await panel.getByRole('button', { name: '确认清空' }).click();
  await expect(editor).toHaveValue('');
  await expect(panel.getByRole('status')).toHaveText('已保存');
  await panel.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(editor).toHaveValue(toggled);
  await expect(panel.getByRole('status')).toHaveText('已保存');
  await panel.getByRole('button', { name: '预览', exact: true }).click();
  await page.screenshot({ path: 'artifacts/scratchpad-desktop.png' });
});

test('offline drafts recover after refresh and conflicting edits never silently overwrite the server', async ({ page, request }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '打开随手记', exact: true }).click();
  const panel = page.getByRole('complementary', { name: '随手记', exact: true });
  await panel.getByRole('button', { name: '源码', exact: true }).click();
  const editor = panel.getByRole('textbox', { name: '随手记内容' });
  await expect(editor).toBeEnabled();
  await page.route('**/api/scratchpad', route => route.request().method() === 'PATCH' ? route.abort() : route.continue());
  await editor.fill('我的未保存想法');
  await expect(panel.getByRole('status')).toHaveText('保存未完成');
  await page.reload();
  await expect(editor).toHaveValue('我的未保存想法');
  await expect(panel.getByRole('status')).toHaveText('保存未完成');
  const current = await (await request.get('/api/scratchpad')).json() as Scratchpad;
  const response = await request.patch('/api/scratchpad', { data: { ...current, content: '手机上写的新内容' }, headers: await mutationHeaders(request) });
  expect(response.ok()).toBe(true);
  await page.unroute('**/api/scratchpad');
  await panel.getByRole('button', { name: '重试', exact: true }).click();
  await expect(panel.getByRole('status')).toHaveText('需要核对');
  await expect(editor).toHaveValue('我的未保存想法');
  expect(((await (await request.get('/api/scratchpad')).json()) as Scratchpad).content).toBe('手机上写的新内容');
  await page.reload();
  await expect(panel.getByRole('status')).toHaveText('需要核对');
  await expect(editor).toHaveValue('我的未保存想法');
  await panel.getByRole('button', { name: '使用最新内容' }).click();
  await expect(editor).toHaveValue('手机上写的新内容');
  await panel.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(editor).toHaveValue('我的未保存想法');
  await expect(panel.getByRole('status')).toHaveText('已保存');
});

